export function createReview() {
  const items = [];
  return {
    add(item) { items.push(item); },
    reset() { items.length = 0; },
    get items() { return [...items]; },
  };
}

const NAMED_ENTITIES = { lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };

// Decodes entities in one pass so &amp;lt; becomes the text "&lt;", not "<".
const decodeEntities = (s) =>
  s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (match, name) => {
    if (name[0] === "#") {
      const code = name[1] === "x" || name[1] === "X" ? parseInt(name.slice(2), 16) : parseInt(name.slice(1), 10);
      return Number.isFinite(code) && code <= 0x10ffff ? String.fromCodePoint(code) : match;
    }
    if (name === "amp") return "&";
    return NAMED_ENTITIES[name.toLowerCase()] ?? match;
  });

const excerpt = (html) => {
  const text = decodeEntities(
    String(html)
      .replace(/<span class="site-kit-flag__note"[^>]*>[\s\S]*?<\/span>/g, "")
      .replace(/<[^>]+>/g, ""),
  )
    .replace(/\s+/g, " ")
    .trim();
  return text.length > 90 ? `${text.slice(0, 87)}…` : text;
};

const plural = (n, word) => `${n} ${word}${n === 1 ? "" : "s"}`;

export function formatReview(items) {
  const lines = [
    "<!-- Generated by site-kit on every build. Do not edit by hand. -->",
    "# Content review",
    "",
    "This list is generated from the site's content flags. Each item needs to be confirmed, replaced or approved. Reply with the item number and your answer (for example, '7: yes, that is correct'). Numbers can change between drafts, so please quote the page too.",
    "",
    "What the labels mean: **CONFIRM**: please check this is true. **NEW**: new wording to approve. **MADE UP**: a stand-in detail; please supply the real one. **STOCK**: a stock or generated image to replace. **PHOTO**: a photo that's needed.",
    "",
  ];
  if (items.length === 0) return [...lines, "No open items.", ""].join("\n");

  const groups = new Map();
  for (const i of items) {
    const key = JSON.stringify([i.type, i.note, String(i.text)]);
    const group = groups.get(key) ?? { ...i, pages: new Map() };
    if (!group.pages.has(i.url)) group.pages.set(i.url, i.title);
    groups.set(key, group);
  }
  const entries = [...groups.values()];
  const sitewide = entries.filter((g) => g.pages.size > 1);
  const perPage = entries.filter((g) => g.pages.size === 1);

  const counts = {};
  for (const g of entries) counts[g.type] = (counts[g.type] ?? 0) + 1;
  const summary = Object.keys(counts).sort().map((t) => `${counts[t]} ${t}`).join(", ");
  lines.push(`**${plural(entries.length, "item")}**: ${summary}`, "");

  let n = 0;
  const itemLine = (g) => {
    const text = excerpt(g.text);
    return `${++n}. **${g.type}**: ${g.note}${text ? ` — “${text}”` : ""}`;
  };

  const sizes = [...new Set(sitewide.map((g) => g.pages.size))].sort((a, b) => b - a);
  for (const size of sizes) {
    lines.push(`## Sitewide (appears on ${size} pages)`, "");
    for (const g of sitewide.filter((x) => x.pages.size === size)) {
      const line = itemLine(g);
      const indent = " ".repeat(line.indexOf(" ") + 1);
      lines.push(line, `${indent}- Pages: ${[...g.pages.keys()].sort().join(", ")}`);
    }
    lines.push("");
  }

  const byPage = new Map();
  for (const g of perPage) {
    const [[url, title]] = g.pages;
    const page = byPage.get(url) ?? { title, items: [] };
    page.title ||= title;
    page.items.push(g);
    byPage.set(url, page);
  }
  for (const url of [...byPage.keys()].sort()) {
    const { title, items: pageItems } = byPage.get(url);
    lines.push(title ? `## ${title} — \`${url}\`` : `## \`${url}\``, "");
    for (const g of pageItems) lines.push(itemLine(g));
    lines.push("");
  }
  return lines.join("\n");
}

export function assertLaunchReady(items) {
  if (items.length === 0) return;
  const list = items.map((i) => `  ${i.url} — ${i.type}: ${i.note}`).join("\n");
  throw new Error(`Launch blocked: ${plural(items.length, "open review item")}.\n${list}`);
}

export function assertNoPlaceholders(keys) {
  if (keys.length === 0) return;
  throw new Error(`Launch blocked: placeholder facts remain: ${keys.join(", ")}`);
}
