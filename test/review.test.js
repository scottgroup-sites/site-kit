import { test } from "node:test";
import assert from "node:assert/strict";
import { FLAG_TYPES, PHOTO_ASPECTS, renderFlag, renderPhoto } from "../src/review/render.js";
import { createReview, formatReview, assertLaunchReady, assertNoPlaceholders } from "../src/review/collect.js";
import { flagMode } from "../src/review/mode.js";

const config = { productionBranch: "main", flags: { production: "fail" } };

test("flag types and photo aspects", () => {
  assert.deepEqual(FLAG_TYPES, ["CONFIRM", "NEW", "MADE UP", "STOCK"]);
  assert.deepEqual(PHOTO_ASPECTS, ["1/1", "4/3", "3/2", "16/9", "21/9", "3/4", "2/3", "4/5"]);
});

test("renderFlag shows text with a data attribute and a hidden-from-screen-readers note", () => {
  assert.equal(
    renderFlag("eight residents", "CONFIRM", "How many?"),
    '<span class="site-kit-flag" data-flag="CONFIRM" data-flag-note="How many?">eight residents<span class="site-kit-flag__note" aria-hidden="true">⚑ CONFIRM: How many?</span></span>',
  );
});

test("renderFlag in hide mode returns the text alone", () => {
  assert.equal(renderFlag("eight residents", "CONFIRM", "How many?", { mode: "hide" }), "eight residents");
});

test("renderFlag escapes notes and rejects bad input", () => {
  assert.match(renderFlag("x", "NEW", 'a <b> & "c"'), /data-flag-note="a &lt;b&gt; &amp; &quot;c&quot;"/);
  assert.throws(() => renderFlag("x", "MAYBE", "n"), /Unknown flag type "MAYBE"/);
  assert.throws(() => renderFlag("x", "NEW", ""), /needs a note/);
});

test("renderPhoto uses an aspect class, never an inline style", () => {
  const html = renderPhoto("Front garden", "16/9");
  assert.match(html, /^<div class="site-kit-photo site-kit-photo--16x9" role="img" aria-label="Photo coming soon: Front garden">/);
  assert.match(html, /<span class="site-kit-photo__label" aria-hidden="true">PHOTO NEEDED: Front garden<\/span>/);
  assert.ok(!html.includes("style="));
  const clean = renderPhoto("Front garden", "4/3", { mode: "hide" });
  assert.match(clean, /^<div class="site-kit-photo site-kit-photo--clean site-kit-photo--4x3" role="img" aria-label="Photo coming soon">/);
  assert.ok(!clean.includes("PHOTO NEEDED"));
  assert.throws(() => renderPhoto("x", "5/2"), /aspect ratio/);
});

test("createReview collects and resets", () => {
  const r = createReview();
  r.add({ url: "/", title: "Home", type: "NEW", note: "n", text: "t" });
  assert.equal(r.items.length, 1);
  r.reset();
  assert.equal(r.items.length, 0);
});

test("formatReview: neutral intro, numbering, sitewide grouping, excerpts without the note", () => {
  const md = formatReview([
    { url: "/about/", title: "About", type: "CONFIRM", note: "How many?", text: renderFlag("eight <b>residents</b>", "CONFIRM", "How many?") },
    { url: "/", title: "Home", type: "MADE UP", note: "Licence number?", text: "Licence #000000" },
    { url: "/about/", title: "About", type: "MADE UP", note: "Licence number?", text: "Licence #000000" },
    { url: "/", title: "Home", type: "PHOTO", note: "Front garden", text: "" },
  ]);
  assert.match(md, /^<!-- Generated by site-kit on every build\. Do not edit by hand\. -->/);
  assert.match(md, /^# Content review$/m);
  assert.match(md, /Reply with the item number and your answer/);
  assert.match(md, /\*\*3 items\*\*: 1 CONFIRM, 1 MADE UP, 1 PHOTO/);
  assert.match(md, /^## Sitewide \(appears on 2 pages\)$/m);
  assert.match(md, /^1\. \*\*MADE UP\*\*: Licence number\? — “Licence #000000”$/m);
  assert.match(md, /Pages: \/, \/about\//);
  assert.match(md, /\*\*CONFIRM\*\*: How many\? — “eight residents”$/m);
  assert.ok(!md.includes("⚑"));
});

test("formatReview with no items", () => {
  assert.match(formatReview([]), /No open items\./);
});

test("launch guards list what blocks launch", () => {
  assert.doesNotThrow(() => assertLaunchReady([]));
  assert.throws(() => assertLaunchReady([{ url: "/", type: "NEW", note: "Approve?" }]), /Launch blocked: 1 open review item\.\n  \/ — NEW: Approve\?/);
  assert.doesNotThrow(() => assertNoPlaceholders([]));
  assert.throws(() => assertNoPlaceholders(["email", "hours"]), /placeholder facts remain: email, hours/);
});

test("flagMode: override, Cloudflare production, Cloudflare preview, local", () => {
  assert.equal(flagMode({ SITE_KIT_FLAGS: "hide" }, config), "hide");
  assert.throws(() => flagMode({ SITE_KIT_FLAGS: "maybe" }, config), /SITE_KIT_FLAGS/);
  assert.equal(flagMode({ CF_PAGES: "1", CF_PAGES_BRANCH: "main" }, config), "fail");
  assert.equal(flagMode({ CF_PAGES: "1", CF_PAGES_BRANCH: "main" }, { ...config, flags: { production: "hide" } }), "hide");
  assert.equal(flagMode({ CF_PAGES: "1", CF_PAGES_BRANCH: "content/new-post" }, config), "hide");
  assert.equal(flagMode({}, config), "show");
});

test("formatReview decodes HTML entities in excerpts, with &amp; decoded last", () => {
  const md = formatReview([
    { url: "/", title: "Home", type: "NEW", note: "Check wording", text: "Tom &amp; Jerry&#39;s" },
    { url: "/", title: "Home", type: "NEW", note: "Literal entity", text: "&amp;lt;b&amp;gt;" },
    { url: "/", title: "Home", type: "NEW", note: "Named and hex", text: "a&nbsp;b &quot;c&quot; &apos;d&apos; &#x41;&#66;" },
  ]);
  assert.match(md, /— “Tom & Jerry's”$/m);
  assert.match(md, /— “&lt;b&gt;”$/m);
  assert.match(md, /— “a b "c" 'd' AB”$/m);
});

test("formatReview strips flag notes that contain newlines", () => {
  const md = formatReview([
    { url: "/", title: "Home", type: "CONFIRM", note: "line one\nline two", text: renderFlag("eight residents", "CONFIRM", "line one\nline two") },
  ]);
  assert.ok(!md.includes("⚑"));
  assert.match(md, /— “eight residents”$/m);
});

test("renderFlag and renderPhoto reject unknown modes; fail renders like show", () => {
  assert.throws(() => renderFlag("x", "NEW", "n", { mode: "maybe" }), /Unknown flag mode "maybe"/);
  assert.throws(() => renderPhoto("x", "4/3", { mode: "maybe" }), /Unknown flag mode "maybe"/);
  assert.equal(renderFlag("x", "NEW", "n", { mode: "fail" }), renderFlag("x", "NEW", "n"));
  assert.equal(renderPhoto("x", "4/3", { mode: "fail" }), renderPhoto("x", "4/3"));
});
